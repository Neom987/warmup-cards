def load(name):
    with open(os.path.join(CARDS, name), encoding="utf-8") as f:
        return json.load(f)


def dump(name, obj):
    with open(os.path.join(CARDS, name), "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
        f.write("\n")


def main():
    log = []
    for t in (1, 2, 3):
        arr = load(f"tier{t}.json")
        titles = {c["title"] for c in arr}
        dropped, patched = [], []

        keep = []
        for c in arr:
            if c["title"] in DROP[t]:
                dropped.append(c["title"])
                continue
            if c["title"] in PATCH:
                c.update(PATCH[c["title"]])
                patched.append(c["title"])
            keep.append(c)

        for title in DROP[t]:
            if title not in titles:
                log.append(f"!! L{t} 要删的「{title}」不存在")

        for title, alt in ALT.items():
            for c in keep:
                if c["title"] == title:
                    c["alt"] = alt

        added = ADD[t]
        for c in added:
            if c["title"] in {x["title"] for x in keep}:
                log.append(f"!! L{t} 新增标题撞车：{c['title']}")
        keep.extend(added)

        if len(keep) != 120:
            log.append(f"!! L{t} 张数 {len(keep)} != 120")
        dump(f"tier{t}.json", keep)
        log.append(f"L{t}: 删 {len(dropped)} 补 {len(added)} 改 {len(patched)} → {len(keep)} 张")
        log.append(f"    删：{'、'.join(dropped)}")

    # 道具库
    props = load("props.json")
    pc = 0
    for c in props["cards"]:
        if c["title"] in PROP_PATCH:
            c.update(PROP_PATCH[c["title"]])
            pc += 1
    req = props.setdefault("requires", {})
    rc = 0
    for title, keys in REQUIRES_ADD.items():
        if title not in req:
            req[title] = keys
            rc += 1
    dump("props.json", props)
    log.append(f"道具卡重分类 {pc} 张 / 新增 requires {rc} 条")

    print("\n".join(log))
    return 0


if __name__ == "__main__":
    sys.exit(main())
