def main():
    changed = 0
    for t in (1, 2, 3):
        p = os.path.join(CARDS, f"tier{t}.json")
        with open(p, encoding="utf-8") as f:
            arr = json.load(f)
        hit = 0
        for c in arr:
            if c["title"] in R:
                c.update(R[c["title"]])
                hit += 1
        with open(p, "w", encoding="utf-8") as f:
            json.dump(arr, f, ensure_ascii=False, indent=1)
            f.write("\n")
        print(f"L{t}: 改写 {hit} 张")
        changed += hit
    missing = [k for k in R if k not in
               {c["title"] for t in (1, 2, 3)
                for c in json.load(open(os.path.join(CARDS, f"tier{t}.json"), encoding="utf-8"))}]
    if missing:
        print("!! 未命中的标题：", "、".join(missing))
    print(f"合计改写 {changed} 张")
    return 0


if __name__ == "__main__":
    sys.exit(main())
