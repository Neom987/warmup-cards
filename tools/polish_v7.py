def main():
    total = 0
    for t in (1, 2, 3):
        p = os.path.join(CARDS, f"tier{t}.json")
        with open(p, encoding="utf-8") as f:
            arr = json.load(f)
        hit = 0
        for c in arr:
            if c["title"] in P:
                c.update(P[c["title"]])
                hit += 1
        with open(p, "w", encoding="utf-8") as f:
            json.dump(arr, f, ensure_ascii=False, indent=1)
            f.write("\n")
        print(f"L{t}: 修正 {hit} 张")
        total += hit
    print(f"合计 {total} 张")
    return 0


if __name__ == "__main__":
    sys.exit(main())
